export const copy = (language: Language, text: string): string =>
  language === "en"
    ? text
    : participantCopy[text as keyof typeof participantCopy]?.[language] || text;
export function participantError(language: Language, text: string) {
  if (language === "en") return text;
  const known = participantCopy[text as keyof typeof participantCopy];
  if (known) return known[language];
  if (Object.values(participantCopy).some((v) => v[language] === text))
    return text;
  return language === "es"
    ? "No se ha podido completar esta acción. Reinténtalo o contacta con el equipo. Puedes usar una respuesta escrita; el progreso ya guardado se conserva."
    : "Cette action n’a pas pu être effectuée. Réessayez ou contactez l’équipe. Vous pouvez répondre par écrit ; la progression déjà enregistrée est conservée.";
}
